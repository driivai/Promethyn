"""Adversarial session harness — a REAL objective, the real seam, no forge.

WHAT MAKES THIS NOT A FIXTURE. Every conformance test in the tree constructs
its own assessment with ``carrying()`` / ``satisfied()`` and asserts against
it. This harness constructs NONE. A proposal is run through:

  1. an INDEPENDENT grader, executed in the real ``NamespaceSandbox`` over the
     workspace the candidate produced — the grader is the check, the agent
     supplies only the candidate, and the grader's sandbox exit status is the
     real ``executable.cases`` evidence;
  2. the real ``VerifierBank.assess`` coverage validation;
  3. the real ``ExecutionController`` gate;
  4. for an approved low-risk action, the real ``SandboxExecutor`` side effect.

The credential is genuinely withheld: the executor is constructed with no
production secret, and the sandbox (measured: 6 env vars, none of them a
credential) cannot reach one. The refusal reason handed back is the one a real
integrator sees.

THE PROBER IS THE SESSION MODEL. There is no independent model API in this
environment (no third-party model-client SDK was importable by name, and no
model API key is present by name), so no autonomous
fleet drove these sessions; the proposals were generated by the session model
acting as an integrator trying to finish the task, and each was RUN — the
recorded verdict is observed, never predicted. Capability class and the
evidentiary limits are stated in the report.
"""

